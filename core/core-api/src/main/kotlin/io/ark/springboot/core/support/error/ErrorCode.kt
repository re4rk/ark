    USER_EMAIL_ALREADY_EXISTS,
    USER_USERNAME_ALREADY_EXISTS,

    // 사용자 비밀번호 관련 오류
    PASSWORD_TOO_SHORT,
    PASSWORD_TOO_LONG,
    PASSWORD_NO_LETTER,
    PASSWORD_NO_DIGIT,
    PASSWORD_NO_SPECIAL,
    PASSWORD_INVALID,

    // 검증 오류
    INVALID_FEED_ID,
    INVALID_AUTHOR_ID,
    INVALID_ENUM_VALUE,
    VALIDATION_ERROR,
    INVALID_REQUEST_FORMAT,
}
